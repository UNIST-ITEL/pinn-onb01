@lru_cache(maxsize=256)
def saturation_properties(
    fluid: str,
    P: float = 101_325.0,
) -> SaturationProperties:
    """Compute saturation-state thermophysical properties using CoolProp.

    Parameters
    ----------
    fluid : str
        Project-facing fluid identifier. Case-insensitive.
        Supported: 'water', 'R-123', 'R-134a', 'Novec649'.
        Unsupported (CoolProp 7.2): 'FC-72', 'FC-77', 'HFE-7100'.
    P : float
        Absolute pressure [Pa]. Must be in [1 kPa, 22.064 MPa].

    Returns
    -------
    SaturationProperties
        Frozen dataclass with all saturation properties.

    Raises
    ------
    UnsupportedFluidError
        If the fluid is known but unavailable in CoolProp 7.2.
    ValueError
        If the fluid is completely unrecognised.
    PressureRangeError
        If P is outside [_P_MIN, _P_MAX].
    AboveCriticalPressureError
        If P exceeds the fluid's critical pressure.

    Notes
    -----
    Results are LRU-cached by (fluid, P) to avoid redundant CoolProp calls
    during batch loss-function evaluations in the PINN training loop.

    CoolProp output keys used:
        'T'       — temperature  [K]
        'D'       — density      [kg/m^3]
        'I'       — surface tension [N/m]
        'H'       — specific enthalpy [J/kg]
        'V'       — dynamic viscosity [Pa·s]
        'L'       — thermal conductivity [W/(m·K)]
        'C'       — isobaric specific heat [J/(kg·K)]
        'Prandtl' — Prandtl number [—]
    """
    fluid_key = fluid.strip().lower()

    # --- fluid validation ---
    if fluid_key in _UNSUPPORTED_FLUIDS:
        raise UnsupportedFluidError(
            f"Fluid '{fluid}' is not supported in CoolProp 7.2.\n"
            f"Reason: {_UNSUPPORTED_FLUIDS[fluid_key]}\n"
            f"Supported fluids: {_SUPPORTED_NAMES}"
        )
    if fluid_key not in _FLUID_MAP:
        raise ValueError(
            f"Unknown fluid '{fluid}'. "
            f"Supported fluids: {_SUPPORTED_NAMES}. "
            f"Unsupported (FC-72, FC-77, HFE-7100) require user-defined tables."
        )

    cp_name: str = _FLUID_MAP[fluid_key]

    # --- pressure range validation (global bound) ---
    if not (_P_MIN <= P <= _P_MAX):
        raise PressureRangeError(
            f"Pressure P={P:.4g} Pa is outside the valid range "
            f"[{_P_MIN:.4g}, {_P_MAX:.4g}] Pa."
        )

    # --- above critical pressure check (per fluid) ---
    p_crit: float = _CP.PropsSI("Pcrit", cp_name)
    if P >= p_crit:
        raise AboveCriticalPressureError(
            f"P={P:.4g} Pa exceeds the critical pressure of {cp_name} "
            f"({p_crit:.4g} Pa). Cannot compute saturation properties."
        )

    # --- CoolProp calls: liquid side (Q=0) ---
    def _liq(output: str) -> float:
        return _CP.PropsSI(output, "P", P, "Q", 0, cp_name)

    def _vap(output: str) -> float:
        return _CP.PropsSI(output, "P", P, "Q", 1, cp_name)

    T_sat = _liq("T")
    rho_l = _liq("D")
    rho_v = _vap("D")
    sigma  = _liq("I")
    h_l    = _liq("H")
    h_v    = _vap("H")
    h_fg   = h_v - h_l
    mu_l   = _liq("V")
    k_l    = _liq("L")
    cp_l   = _liq("C")
    Pr_l   = _liq("Prandtl")
    nu_l   = mu_l / rho_l

    return SaturationProperties(
        fluid=fluid,
        P=P,
        T_sat=T_sat,
        rho_l=rho_l,
        rho_v=rho_v,
        sigma=sigma,
        h_fg=h_fg,
        mu_l=mu_l,
        k_l=k_l,
        cp_l=cp_l,
        Pr_l=Pr_l,
        nu_l=nu_l,
    )


