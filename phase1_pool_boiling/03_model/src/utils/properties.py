def jacob_number(
    props: SaturationProperties,
    delta_T_sub: float,
) -> float:
    """Jacob number for subcooled pool boiling.

    Ja = (rho_l * cp_l * delta_T_sub) / (rho_v * h_fg)

    Parameters
    ----------
    props : SaturationProperties
        Saturation properties at the operating pressure.
    delta_T_sub : float
        Liquid subcooling, T_sat - T_bulk [K].  Must be >= 0.

    Returns
    -------
    float
        Jacob number [—].
    """
    if delta_T_sub < 0.0:
        raise ValueError(
            f"delta_T_sub must be >= 0 (got {delta_T_sub:.4g} K). "
            "Subcooling is defined as T_sat - T_bulk."
        )
    return (props.rho_l * props.cp_l * delta_T_sub) / (props.rho_v * props.h_fg)


def capillary_length(
    props: SaturationProperties,
    g: float = _G,
) -> float:
    """Capillary (Laplace) length scale for bubble departure.

    L_c = sqrt(sigma / (g * (rho_l - rho_v)))

    Parameters
    ----------
    props : SaturationProperties
        Saturation properties at the operating pressure.
    g : float
        Gravitational acceleration [m/s^2]. Default = 9.80665 m/s^2.

    Returns
    -------
    float
        Capillary length [m].
    """
    return math.sqrt(props.sigma / (g * (props.rho_l - props.rho_v)))


def hsu_criterion_cavity_radius(
    props: SaturationProperties,
    delta_T_wall: float,
    q_flux: float,
) -> tuple[float, float]:
    """Active nucleation cavity radius range from Hsu (1962).

    Hsu's criterion identifies the range of cavity mouth radii (r_c_min, r_c_max)
    that can sustain nucleation for given wall superheat and heat flux.

    The derivation considers the temperature profile in the thermal boundary
    layer (natural convection) and the Clausius-Clapeyron vapour equilibrium
    at the bubble tip. The exact quadratic solution is:

        B = (2 * sigma * T_sat) / (rho_v * h_fg)     [m·K]

        r_c_{min,max} = (k_l * delta_T_wall) / (2 * q_flux)
                        * (1 ± sqrt(1 - 8 * sigma * T_sat / (rho_v * h_fg^2
                                     * (k_l * delta_T_wall / q_flux))))

    where the minus sign gives r_c_min and the plus sign gives r_c_max.

    If the discriminant is negative, no cavity satisfies the criterion at the
    given conditions (returns (0.0, 0.0) with a warning embedded in the
    docstring; callers should check for this).

    Parameters
    ----------
    props : SaturationProperties
        Saturation properties at the operating pressure.
    delta_T_wall : float
        Wall superheat, T_wall - T_sat [K].  Must be > 0.
    q_flux : float
        Surface heat flux [W/m^2].  Must be > 0.

    Returns
    -------
    tuple[float, float]
        (r_c_min, r_c_max) in [m].  Both are 0.0 if no solution exists.

    References
    ----------
    Hsu, Y.Y. (1962). On the size range of active nucleation cavities on a
    heating surface. J. Heat Transfer, 84(3), 207-216.
    """
    if delta_T_wall <= 0.0:
        raise ValueError(
            f"delta_T_wall must be > 0 (got {delta_T_wall:.4g} K). "
            "Wall superheat is T_wall - T_sat."
        )
    if q_flux <= 0.0:
        raise ValueError(f"q_flux must be > 0 (got {q_flux:.4g} W/m^2).")

    # half-boundary-layer thickness scale: delta_t = k_l * delta_T_wall / q_flux
    delta_t: float = props.k_l * delta_T_wall / q_flux  # [m]

    # Hsu discriminant factor
    #   discriminant = 1 - 8 * sigma * T_sat / (rho_v * h_fg^2 * delta_t)
    # (derived by substituting Clausius-Clapeyron linearisation into the
    #  temperature boundary condition at the bubble tip at height r_c(1+cos θ),
    #  simplified for θ = 53.1° → factor 8/C_sf where C_sf ≈ 1 in Hsu's original)
    discriminant: float = (
        1.0
        - (8.0 * props.sigma * props.T_sat)
        / (props.rho_v * props.h_fg**2 * delta_t / props.cp_l)
        # Note: Hsu's quadratic contains cp_l * delta_T_wall / h_fg
        # Full exact form from Hsu (1962) eq. 13:
    )

    # Re-derive with Hsu's exact grouping (eq. 13 in the original paper):
    #   discriminant_exact = 1 - (8 * sigma * T_sat * cp_l) /
    #                             (rho_v * h_fg^2 * delta_t)
    discriminant_exact: float = (
        1.0
        - (8.0 * props.sigma * props.T_sat * props.cp_l)
        / (props.rho_v * props.h_fg**2 * delta_t)
    )

    if discriminant_exact < 0.0:
        # No active cavity exists at these conditions
        return (0.0, 0.0)

    sqrt_disc: float = math.sqrt(discriminant_exact)

    # r_c = (delta_t / 2) * (1 ± sqrt_disc)
    r_c_min: float = (delta_t / 2.0) * (1.0 - sqrt_disc)
    r_c_max: float = (delta_t / 2.0) * (1.0 + sqrt_disc)

    return (r_c_min, r_c_max)


